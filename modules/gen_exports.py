"""Regenerate the export lists of beman.inside.cppm and beman.inside.units.cppm.

Runs clang's JSON AST dump over the public headers and collects every name
declared (or brought in by a using-declaration) at namespace scope in
beman::inside and its public namespaces: not detail, not math::adaptive
(its public names reach math through cmath.hpp's using-declarations), not
the units *_defs namespaces (the objects behind the tags). Out-of-line
member definitions are skipped. Each module file is rewritten below its
"// --- exports (generated" marker.

Usage: python3 modules/gen_exports.py [--cxx clang++-20]   (from the repo root)
"""
import argparse
import collections
import json
import os
import subprocess
import tempfile

HEADERS_CORE = ["inside", "io", "cmath", "formats", "numeric_limits", "random", "predicates"]
HEADERS_UNITS = ["units", "units_math"]
KINDS = {"FunctionTemplateDecl", "FunctionDecl", "CXXRecordDecl", "ClassTemplateDecl", "VarTemplateDecl",
         "ConceptDecl", "TypeAliasDecl", "TypeAliasTemplateDecl", "TypedefDecl", "VarDecl", "EnumDecl", "UsingDecl"}
SKIP_NAMESPACES = {"detail", "adaptive", "si_defs", "isq_defs", "international_defs", "si2019_defs"}
MARKER = "// --- exports (generated by modules/gen_exports.py; do not edit below) ---"


def dump_ast(cxx: str) -> list:
    with tempfile.TemporaryDirectory() as td:
        src = os.path.join(td, "all.cpp")
        with open(src, "w", encoding="utf-8") as f:
            for h in HEADERS_CORE + HEADERS_UNITS:
                f.write(f"#include <beman/inside/{h}.hpp>\n")
        out = subprocess.run([cxx, "-std=c++23", "-Iinclude", "-fsyntax-only", "-Xclang", "-ast-dump=json",
                              "-Xclang", "-ast-dump-filter=beman", src], capture_output=True, text=True, check=True)
    dec, i, objs, data = json.JSONDecoder(), 0, [], out.stdout
    while i < len(data):
        while i < len(data) and data[i].isspace():
            i += 1
        if i < len(data):
            o, i = dec.raw_decode(data, i)
            objs.append(o)
    return objs


def collect(objs: list) -> dict:
    names = collections.defaultdict(dict)  # namespace -> name -> declaring header

    def file_of(n):
        loc = n.get("loc", {})
        return loc.get("file") or loc.get("spellingLoc", {}).get("file") or loc.get("expansionLoc", {}).get("file")

    def walk(n, ns, last_file):
        f = file_of(n) or last_file
        kind = n.get("kind")
        if kind == "NamespaceDecl":
            name = n.get("name", "")
            if name and name not in SKIP_NAMESPACES:
                for c in n.get("inner", []):
                    walk(c, ns + [name], f)
            return
        if ns[:2] != ["beman", "inside"] or kind not in KINDS or n.get("isImplicit"):
            return
        name = n.get("name")
        if not name:
            return
        if kind == "UsingDecl":
            name = name.split("::")[-1]
        inner = [c for c in n.get("inner", []) if isinstance(c, dict)]
        if "parentDeclContextId" in n or any("parentDeclContextId" in c for c in inner):
            return  # an out-of-line member definition
        names["::".join(ns)].setdefault(name, f)

    for o in objs:
        if o.get("kind") == "NamespaceDecl" and o.get("name") == "beman":
            walk(o, [], None)
    return names


def using_block(names: dict, ns: str, via: str, indent: str) -> list:
    out, last = [], None
    for name, f in sorted(names.get(ns, {}).items(), key=lambda nf: (nf[1] or "", nf[0])):
        header = os.path.relpath(f, "include") if f else "?"
        if header != last:
            out.append(f"{indent}// {header}")
            last = header
        out.append(f"{indent}using {via}::{name};")
    return out


def rewrite(path: str, lines: list) -> None:
    with open(path, encoding="utf-8") as f:
        text = f.read()
    head = text[: text.index(MARKER) + len(MARKER)]
    with open(path, "w", encoding="utf-8") as f:
        f.write(head + "\n" + "\n".join(lines) + "\n")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--cxx", default="clang++-20")
    args = ap.parse_args()
    names = collect(dump_ast(args.cxx))

    core = ["export namespace beman::inside {"]
    core += using_block(names, "beman::inside", "beman::inside", "    ")
    core += using_block(names, "beman::inside::small_grids_v2", "beman::inside", "    ")  # the inline ABI namespace
    core += ["", "namespace math {"] + using_block(names, "beman::inside::math", "beman::inside::math", "    ")
    core += ["} // namespace math", "} // namespace beman::inside"]
    rewrite("modules/beman.inside.cppm", core)

    units = ["export namespace beman::inside::units {"]
    units += using_block(names, "beman::inside::units", "beman::inside::units", "    ")
    for sub in ("si", "isq", "international", "si2019"):
        ns = f"beman::inside::units::{sub}"
        units += ["", f"namespace {sub} {{"] + using_block(names, ns, ns, "    ") + [f"}} // namespace {sub}"]
    units += ["} // namespace beman::inside::units"]
    rewrite("modules/beman.inside.units.cppm", units)
    print({ns: len(v) for ns, v in sorted(names.items())})


if __name__ == "__main__":
    main()

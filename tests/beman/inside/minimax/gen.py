"""Regenerate include/beman/inside/math/detail/minimax.hpp with Sollya.

    python3 tests/beman/inside/minimax/gen.py

Needs sollya (8.0) on PATH; nothing else does: the generated header is plain
C++ and the library, its tests and CI never run Sollya. Each fit's interval
must match the kernel's argument range in math/detail/fp.hpp (the constants
below are those of fp.hpp, as doubles).
"""

import pathlib
import re
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[3]
OUT = ROOT / "include/beman/inside/math/detail/minimax.hpp"

# name, function, odd, interval (Sollya expressions), terms, what it is
FITS = [
    ("asin", "asin(x)", 1, "0", "1/2", 2, 15, "asin x ≈ x·q(x²) on [0, ½]"),
    ("exp", "exp(x)", 0, "-0x1.63p-2", "0x1.63p-2", 3, 13, "e^r ≈ q(r) on |r| ≤ r_exp"),
    ("atanh", "atanh(x)", 1, "0", "round(0.1716, D, RN)", 2, 9, "atanh f ≈ f·q(f²) on |f| ≤ f_max (log)"),
    ("atan", "atan(x)", 1, "0", "round(0.2681, D, RN)", 2, 11, "atan t ≈ t·q(t²) on |t| ≤ t_max"),
]


def run_sollya() -> dict:
    program = (HERE / "minimax.sollya").read_text()
    for name, f, odd, a, b, lo, hi, _ in FITS:
        program += f'fit("{name}", {f}, {odd}, {a}, {b}, {lo}, {hi});\n'
    program += "quit;\n"
    version = subprocess.run(["sollya", "--help"], capture_output=True, text=True).stdout.split("\n")[0]
    out = subprocess.run(["sollya", "--nocolor"], input=program, capture_output=True, text=True, check=True).stdout
    fits = {}
    for line in out.splitlines():
        if not line.startswith("FIT "):
            continue
        _, name, n, bound, *coeffs = line.split()
        n = int(float.fromhex(n))  # Sollya prints every number in hexadecimal
        if len(coeffs) != n or not all(re.fullmatch(r"-?0x1(\.[0-9a-f]+)?p[+-]?\d+|0", c) for c in [bound, *coeffs]):
            sys.exit(f"unexpected Sollya output: {line}")
        fits.setdefault(name, []).append((n, bound, coeffs))
    return fits, version


def sollya_version(banner: str) -> str:
    m = re.match(r"This is sollya ([0-9.]+)", banner)
    return m.group(1) if m else banner


def literal(c: str) -> str:
    return "0.0" if c == "0" else c


def header(fits: dict, version: str) -> str:
    lines = [
        "// SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception",
        "// GENERATED by tests/beman/inside/minimax/gen.py from minimax.sollya — do not edit.",
        f"// Sollya {sollya_version(version)}.",
        "//",
        "// The double tier's minimax polynomials (math/detail/fp.hpp). Each fit holds",
        "// the coefficients of a polynomial with double coefficients (highest degree",
        "// first) and Err, an upper bound of its relative error |p/f − 1| over the",
        "// interval, certified by Sollya's supnorm (interval arithmetic and Taylor",
        "// models) and rounded up. The kernels prove their bounds with Err as the",
        "// approximation term, as with the Taylor series' first omitted term.",
        "//---------------------------------------------------------------------------",
        "#ifndef BEMAN_INSIDE_MATH_DETAIL_MINIMAX_HPP",
        "#define BEMAN_INSIDE_MATH_DETAIL_MINIMAX_HPP",
        "",
        "#include <array>",
        "#include <cstddef>",
        "",
        "// clang-format off (generated: the fits stay one per line)",
        "namespace beman::inside::math::detail::fp::minimax {",
        "",
        "template <std::size_t N>",
        "struct fit {",
        "    std::array<double, N> C; // highest degree first",
        "    double                Err;",
        "};",
    ]
    for name, f, odd, a, b, lo, hi, what in FITS:
        entries = sorted(fits[name])
        if [n for n, _, _ in entries] != list(range(lo, hi + 1)):
            sys.exit(f"{name}: missing fits")
        lines += ["", f"// {what}: {lo} to {hi} terms.", f"inline constexpr int {name}_min = {lo}, {name}_max = {hi};"]
        lines += ["template <int N>", f"inline constexpr fit<N> {name}_fit{{}};"]
        for n, bound, coeffs in entries:
            body = ", ".join(literal(c) for c in coeffs)
            lines.append(f"template <>")
            lines.append(f"inline constexpr fit<{n}> {name}_fit<{n}>{{{{{body}}}, {literal(bound)}}};")
        errs = ", ".join(literal(bound) for _, bound, _ in entries)
        lines.append(f"inline constexpr std::array<double, {len(entries)}> {name}_err{{{errs}}}; // index terms − min")
    lines += ["", "} // namespace beman::inside::math::detail::fp::minimax", "// clang-format on", "",
              "#endif // BEMAN_INSIDE_MATH_DETAIL_MINIMAX_HPP", ""]
    return "\n".join(lines)


def main() -> None:
    fits, version = run_sollya()
    OUT.write_text(header(fits, version))
    print(f"wrote {OUT.relative_to(ROOT)}: " + ", ".join(f"{k} {len(v)}" for k, v in fits.items()))


if __name__ == "__main__":
    main()
